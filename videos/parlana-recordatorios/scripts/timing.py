"""Word anchors and state starts for the v2 reel, from the voice transcript and the music grid.

Usage (from the video folder): python3 scripts/timing.py
Writes compositions/shared/timing.js, which the compositions and the cue script read.
Rule (MOTION.md): a state change sits on the nearest music beat when that beat is within
150 ms of its word; otherwise the word wins.
"""
import json

words = json.load(open("assets/vo/transcript.json"))
grid = json.load(open("assets/music/grid.json"))
BEATS = grid["beats"]


def at(text, after=0.0, edge="start"):
    for w in words:
        if w["text"].strip("¿?¡!.,:;").lower() == text.lower() and w["start"] >= after:
            return round(w[edge], 2)
    raise SystemExit(f"anchor not found: {text} after {after}")


A = {
    "hora": at("hora", 2.5), "aparecio": at("apareció"),
    "seguramente": at("seguramente"), "listo": at("listo"), "paso": at("pasó"), "llego": at("llegó", 7),
    "noAviso": at("no", 8), "contesta": at("contesta"),
    "quizas": at("quizás"), "tampoco": at("tampoco"), "primera": at("primera"),
    "claro": at("yclaro"), "tiempo": at("tiempo", 13), "reservaste": at("reservaste", 14, "end"), "ingreso": at("ingreso"),
    "envias": at("seguramente", 17), "recordatorios1": at("recordatorios", 17.9), "clientes1": at("clientes", 18.5),
    "pero": at("pero", 19), "atenderlos": at("atenderlos"), "mensajes": at("mensajes"), "ocuparte": at("ocuparte"),
    "implica": at("implica"), "negocio": at("negocio", 23), "tiempo2": at("tiempo", 24), "alguno": at("alguno"),
    "ySi": at("y", 27.4), "automaticamente": at("automáticamente"),
    "unDia": at("un", 31), "anterior": at("anterior", 31), "unas": at("unas"), "antes": at("antes", 32),
    "paraQue": at("para", 32.8), "recuerde": at("recuerde"), "confirmar": at("confirmar"), "reprogramar": at("reprogramar"),
    "yAqui": at("yaquí"), "boliviano": at("boliviano"), "hasta": at("hasta"), "siete": at("7"),
    "mejor": at("mejor"), "sinTener": at("sin", 42.6), "mismo": at("mismo", 43, "end"),
    "porEso": at("por", 44), "parlana": at("parlana", 45), "automatizar": at("automatizar", 46), "gestionar": at("gestionar"),
    "confirmaciones": at("confirmaciones"), "escribir": at("escribir"),
    "peroParlana": at("pero", 52), "responder": at("responder", 55), "consultas": at("consultas"), "agendar": at("agendar"),
    "asi": at("así"), "llegan": at("llegan"), "escriben": at("escriben"), "organizar": at("organizar"), "recordarles": at("recordarles"),
    "gustaria": at("gustaría"), "comenta": at("comenta"), "citasCta": at("citas", 72),
    "end": round(words[-1]["end"], 2),
}


def snap(t):
    b = min(BEATS, key=lambda x: abs(x - t))
    return b if abs(b - t) <= 0.15 else round(t, 3)


# State starts: a little before the word that opens each state, then onto the beat when close.
raw = [0.0, A["noAviso"] - 0.1, A["quizas"] - 0.05, A["claro"] - 0.12, A["envias"] - 0.15, A["pero"] - 0.05,
       A["ySi"] - 0.2, A["unDia"] - 0.2, A["paraQue"] + 0.75, A["yAqui"] - 0.15, A["porEso"] - 0.15,
       A["peroParlana"] - 0.12, A["asi"] - 0.15, A["gustaria"] - 0.55, A["end"] + 0.1]
S = [0.0] + [snap(t) for t in raw[1:]]
END = round(S[-1] + 1.3, 3)
names = ["card", "chat", "weeks", "disc", "list", "busy", "toggle", "timeline", "client", "price", "parlana", "inbox", "split", "cta", "loop"]

with open("compositions/shared/timing.js", "w") as f:
    f.write("/* Generated by scripts/timing.py from assets/vo/transcript.json and assets/music/grid.json. Do not edit by hand. */\n")
    f.write("(function (root) {\n")
    f.write("  root.Timing = " + json.dumps({"A": A, "S": dict(zip(names, S)), "END": END, "BEATS": BEATS, "MEDIA_START": grid["mediaStart"]}, indent=1) + ";\n")
    f.write('})(typeof window !== "undefined" ? window : globalThis);\n')
for n, r, s in zip(names, raw, S):
    print(f"{n:9s} raw {r:6.2f} -> {s:6.2f}{'  (beat)' if s != round(r, 3) else ''}")
print("END", END)
