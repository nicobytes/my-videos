// words.json → compositions/captions.html (chunks of ≤3 words / ≤20 chars,
// split at punctuation). Captions stop when the CTA scene starts (its text is on screen).
// Run: node tools/captions.mjs
import fs from "fs";
const words = JSON.parse(fs.readFileSync("assets/vo/words.json", "utf8"));
const CTA = 31.92;
const chunks = []; let cur = [];
words.filter((w) => w.start < CTA).forEach((w) => {
  const len = cur.map((x) => x.text).join(" ").length + w.text.length + 1;
  if (cur.length && (cur.length >= 3 || len > 20)) { chunks.push(cur); cur = []; }
  cur.push(w);
  if (/[.,?…]$/.test(w.text)) { chunks.push(cur); cur = []; }
});
if (cur.length) chunks.push(cur);
const data = chunks.map((c, i) => {
  const next = chunks[i + 1];
  const end = next ? Math.min(next[0].start, c.at(-1).end + 0.5) : Math.min(c.at(-1).end + 0.4, CTA);
  return { s: c[0].start, e: +end.toFixed(3), w: c.map((x) => [x.text, x.start]) };
});
const html = `<!DOCTYPE html>
<html lang="es">
  <head><meta charset="UTF-8"></head>
  <body>
    <template>
      <style>
        @font-face { font-family: "Jersey 10"; src: url("assets/fonts/jersey10-latin.woff2") format("woff2"); font-weight: 400; }
        @font-face { font-family: "Plus Jakarta Sans"; src: url("assets/fonts/plusjakarta-latin.woff2") format("woff2"); font-weight: 200 800; }
        #captions-root { position: absolute; inset: 0; width: 1080px; height: 1920px; overflow: hidden; pointer-events: none; }
        /* Reels safe zone: plate bottom sits 380px above the frame edge (frame.md) */
        .cg { position: absolute; left: 60px; right: 60px; bottom: 380px; display: flex; justify-content: center; opacity: 0; visibility: hidden; }
        .cp {
          display: flex; gap: 0 18px; flex-wrap: wrap; justify-content: center; background: #00260f; padding: 16px 34px 20px;
          clip-path: polygon(10px 0, calc(100% - 10px) 0, calc(100% - 10px) 10px, 100% 10px, 100% calc(100% - 10px), calc(100% - 10px) calc(100% - 10px), calc(100% - 10px) 100%, 10px 100%, 10px calc(100% - 10px), 0 calc(100% - 10px), 0 10px, 10px 10px);
        }
        .cw { font-family: "Plus Jakarta Sans", sans-serif; font-weight: 800; font-size: 62px; line-height: 1.1; color: #f1efe8; display: block; }
      </style>
      <div id="captions-root" data-composition-id="captions" data-start="0" data-duration="35.3" data-width="1080" data-height="1920"></div>
      <script>
        (function () {
          // generated by tools/captions.mjs from the user's SRT (word times interpolated per cue)
          var CHUNKS = ${JSON.stringify(data)};
          var root = document.getElementById("captions-root");
          var tl = gsap.timeline({ paused: true });
          CHUNKS.forEach(function (c, i) {
            var g = document.createElement("div"); g.className = "cg"; g.id = "cap-" + i;
            var p = document.createElement("div"); p.className = "cp notch"; g.appendChild(p);
            var els = c.w.map(function (w) { var s = document.createElement("span"); s.className = "cw"; s.textContent = w[0]; p.appendChild(s); return s; });
            root.appendChild(g);
            tl.fromTo(g, { autoAlpha: 0, y: 24 }, { autoAlpha: 1, y: 0, duration: 0.1, ease: "steps(2)" }, c.s);
            tl.set(g, { autoAlpha: 0 }, c.e);
            els.forEach(function (el, k) {
              tl.set(el, { color: "#f1efe8" }, c.s);
              tl.set(el, { color: "#00bd4c" }, c.w[k][1]);
              var nx = k < c.w.length - 1 ? c.w[k + 1][1] : c.e;
              tl.set(el, { color: "#f1efe8" }, nx);
            });
          });
          window.__timelines["captions"] = tl;
        })();
      </script>
    </template>
  </body>
</html>
`;
fs.writeFileSync("compositions/captions.html", html);
